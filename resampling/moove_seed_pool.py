#!/usr/bin/env python3
# resampling/moove_seed_pool.py
"""
Build the few-shot seed pool for a new synthetic MOOVE set, with every question
used for evaluation removed.

Why: synthetic_moove_v2 was generated by distill_moove_v2.py, which samples 5
real MOOVE questions per call as few-shot examples, straight from
data/moove/full_moove.jsonl. That pool holds the questions of the unanimous-576
evaluation set -- 487 of its 516 distinct questions. Every synthetic question in
the 24k corpus was therefore written while looking at questions the model is
later judged on: leakage into the training data, even though no answer was
copied.

What counts as "used for evaluation" here, and why:

  * moove_eval_unanimous_576.jsonl -- the head-to-head / judge evaluation set.
    It is built by unanimity filtering over all reviews, not by the train/test
    split, so 443 of its questions sit in the review *train* split and 56 in the
    test split. Being train-split does not make a question safe: it is still
    scored at evaluation time.
  * all_reviews_no_dup_test.jsonl -- the held-out review split.

--keep unanimous|test lets either group back in; the report always states what
was removed, so a pool can never be silently wider than it claims.

usage:
python3 resampling/moove_seed_pool.py \
    --pool data/moove/full_moove.jsonl \
    --out data/moove/full_moove_train_only.jsonl
    --selfcheck   offline unit checks

writes:
    <out>                  pool rows whose question is not an eval question
    <out>.report.json      counts, and the exclusions that produced them
"""

import argparse
import difflib
import json
import re
from pathlib import Path

EVAL_SETS = {
    "unanimous": ("data/moove/moove_eval_unanimous_576.jsonl", ("question",)),
    "test": ("moove/all_reviews_no_dup_test.jsonl",
             ("left_question_text", "right_question_text")),
}


def norm(text):
    """Match on the question's text, not its whitespace, case or punctuation.

    Whitespace and case alone are not enough: 20 of the 516 unanimous-576
    questions differ from their pool copy only in punctuation.
    """
    return re.sub(r"[^a-z0-9]+", " ", (text or "").lower()).strip()


NEAR_RATIO = 0.9       # difflib ratio at which a pool question counts as the eval one


def grams(text, n=6):
    w = norm(text).split()
    return {" ".join(w[i:i + n]) for i in range(max(len(w) - n + 1, 0))}


def near_copies(pool_qs, banned_qs, ratio=NEAR_RATIO):
    """Pool questions within `ratio` of an eval question, beyond exact matches.

    A further 49 unanimous questions sit in the pool at ratio >= 0.9 as a
    prefixed copy ("Question 4 ..."), a line break moved, or the same case with
    the age or sex changed. A 6-gram index keeps this to a few candidates each.
    """
    index = {}
    for i, q in enumerate(pool_qs):
        for g in grams(q):
            index.setdefault(g, set()).add(i)
    hits = set()
    for b in banned_qs:
        shared = {}
        for g in grams(b):
            for i in index.get(g, ()):
                shared[i] = shared.get(i, 0) + 1
        for i, _ in sorted(shared.items(), key=lambda x: -x[1])[:20]:
            if difflib.SequenceMatcher(None, norm(b), norm(pool_qs[i])).ratio() >= ratio:
                hits.add(i)
    return hits


def questions(path, keys):
    """Every distinct question in a file (raw text), over any of `keys`."""
    found = set()
    with open(path, encoding="utf-8") as f:
        for line in f:
            line = line.strip()
            if not line:
                continue
            row = json.loads(line)
            for k in keys:
                v = row.get(k)
                if isinstance(v, str) and v.strip():
                    found.add(v)
    return found


def build(pool_path, out_path, keep=(), root=Path(".")):
    excluded = {}
    banned = set()
    for name, (rel, keys) in EVAL_SETS.items():
        if name in keep:
            excluded[name] = "kept (--keep)"
            continue
        qs = questions(Path(root) / rel, keys)
        excluded[name] = {"file": rel, "distinct_questions": len(qs)}
        banned |= qs

    rows = []
    with open(pool_path, encoding="utf-8") as f:
        for line in f:
            if line.strip():
                rows.append(json.loads(line))
    exact = {norm(q) for q in banned}
    distinct = list({norm(r.get("question", "")): r.get("question", "") for r in rows}.values())
    near = {norm(distinct[i]) for i in near_copies(distinct, banned)} - exact
    kept, dropped, dropped_near = [], 0, 0
    for row in rows:
        key = norm(row.get("question", ""))
        if key in exact:
            dropped += 1
        elif key in near:
            dropped_near += 1
        else:
            kept.append(row)

    out_path = Path(out_path)
    out_path.parent.mkdir(parents=True, exist_ok=True)
    with open(out_path, "w", encoding="utf-8") as f:
        for row in kept:
            f.write(json.dumps(row, ensure_ascii=False) + "\n")

    report = {
        "pool": str(pool_path),
        "out": str(out_path),
        "rows_in": len(rows),
        "rows_kept": len(kept),
        "rows_dropped": dropped + dropped_near,
        "rows_dropped_exact": dropped,
        "rows_dropped_near": dropped_near,
        "near_ratio": NEAR_RATIO,
        "distinct_questions_kept": len({norm(r.get("question", "")) for r in kept}),
        "excluded": excluded,
    }
    with open(str(out_path) + ".report.json", "w", encoding="utf-8") as f:
        json.dump(report, f, indent=2)
    return report


def main():
    p = argparse.ArgumentParser(description=__doc__,
                                formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("--pool", default="data/moove/full_moove.jsonl")
    p.add_argument("--out", default="data/moove/full_moove_train_only.jsonl")
    p.add_argument("--keep", action="append", default=[], choices=list(EVAL_SETS),
                   help="let an eval set back into the pool (not recommended)")
    p.add_argument("--root", default=".", help="repo root the eval paths resolve against")
    p.add_argument("--selfcheck", action="store_true")
    args = p.parse_args()
    if args.selfcheck:
        return _selfcheck()
    print(json.dumps(build(args.pool, args.out, keep=set(args.keep), root=Path(args.root)),
                     indent=2))


def _selfcheck():
    import tempfile
    with tempfile.TemporaryDirectory() as d:
        d = Path(d)
        (d / "data/moove").mkdir(parents=True)
        (d / "moove").mkdir(parents=True)

        def w(p, rows):
            with open(d / p, "w") as f:
                for r in rows:
                    f.write(json.dumps(r) + "\n")

        w("data/moove/moove_eval_unanimous_576.jsonl", [{"question": "  EVAL  question "}])
        w("moove/all_reviews_no_dup_test.jsonl",
          [{"left_question_text": "held out q", "right_question_text": ""}])
        long_eval = ("A 58 year old male presents at Mbagathi County Hospital for routine "
                     "follow-up with a five year history of hypertension on amlodipine")
        w("data/moove/moove_eval_unanimous_576.jsonl",
          [{"question": "  EVAL  question "}, {"question": long_eval}])
        w("data/moove/pool.jsonl", [{"question": "eval question"},      # case/space differ
                                    {"question": "Held Out Q"},
                                    {"question": "Eval, question!"},    # punctuation only
                                    {"question": "Question 4 " + long_eval},  # near copy
                                    {"question": "a clean question"},
                                    {"question": "a clean question"}])  # duplicate row
        rep = build(d / "data/moove/pool.jsonl", d / "out.jsonl", root=d)
        rows = [json.loads(l) for l in open(d / "out.jsonl")]
        assert rep["rows_dropped"] == 4, rep            # exact, punctuation, held-out, near
        assert rep["rows_dropped_near"] == 1, rep
        assert rep["rows_kept"] == 2 and rep["distinct_questions_kept"] == 1
        assert all("clean" in r["question"] for r in rows)
        rep2 = build(d / "data/moove/pool.jsonl", d / "out2.jsonl", keep={"unanimous"}, root=d)
        assert rep2["rows_dropped"] == 1 and rep2["excluded"]["unanimous"] == "kept (--keep)"
        assert "Mbagathi" not in open(d / "out.jsonl").read()
    print("selfcheck ok")


if __name__ == "__main__":
    main()
